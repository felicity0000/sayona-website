export interface ServiceItem {
  title: string;
  desc: string;
  image?: string;
  images?: string[];
}

// A single text+image block within a showcase page (secondary section, banner).
export interface ShowcaseBlock {
  tagline: string;
  heading: string;
  highlight?: string; // substring of `heading` to render in yellow
  description: string;
  image: string;
  imagePosition?: string; // CSS object-position for the banner image; defaults to 'center'
}

// Bespoke "text left, images right, no cards" product page — used instead of
// the generic card grid when present on a ServiceData entry.
export interface ServiceShowcase {
  hero: {
    tagline: string;
    heading: string;
    highlight?: string;
    description: string;
    features: string[];
    mainImage: string;
    sideImages: string[];
    fit: 'contain' | 'cover'; // 'contain': transparent PNG cutouts (floating, drop-shadow). 'cover': real photos (rounded, cropped).
  };
  secondary?: ShowcaseBlock & { fit: 'contain' | 'cover'; secondImage?: string };
  // Grid of real-world / in-use photos, shown as its own section (e.g. customer installs).
  gallery?: {
    tagline: string;
    heading: string;
    highlight?: string;
    description: string;
    images: string[];
  };
  banner?: ShowcaseBlock;
}

export interface ServiceData {
  slug: string;
  icon: LucideIcon;
  image?: string;
  title: string;
  intro: string;
  catalogue?: string;
  items: ServiceItem[];
  showcase?: ServiceShowcase;
}

